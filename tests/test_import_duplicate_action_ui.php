<?php
/**
 * Тест: выбор действия при дубликатах реально доступен в форме импорта.
 *
 * Запуск:  php tests/test_import_duplicate_action_ui.php
 * Код выхода: 0 — прошло, 1 — есть падения.
 *
 * Зачем этот тест существует (найдено 2026-08-10 живой проверкой).
 *
 * Бэкенд импорта поддерживает три режима обработки дубликатов — skip / update /
 * error, — но из интерфейса пользователю был доступен ровно один: форма в
 * templates/dashboard.php отправляла duplicate_action СКРЫТЫМ полем со значением
 * 'skip', и ни один JS его не менял. Радиокнопки с полноценным выбором лежали в
 * templates/partials/dashboard/modals/add-account-modal.php — партиале, который
 * не подключён ниоткуда (греп по всем шаблонам давал ноль включений).
 *
 * То есть рядом с рабочей формой лежала её правдоподобная копия, и правка копии
 * ничего не меняла для пользователя. Заметить это можно было только по
 * отрендеренной странице, а не по чтению шаблонов.
 *
 * Тест стережёт три вещи:
 *  1. в РАБОЧЕМ шаблоне есть настоящий выбор из трёх режимов;
 *  2. значение не зашито скрытым полем (иначе выбор снова станет фикцией);
 *  3. по умолчанию выбран самый безопасный режим — «Пропустить»;
 *  4. перед запуском разрушительного режима «Обновить» спрашивается подтверждение.
 *
 * Почему подтверждение важно: «Обновить» перезаписывает данные существующих
 * аккаунтов, а импорт НЕ пишет в журнал отмены — откатить нечем.
 */

set_error_handler(static function ($no, $str, $file, $line) {
    throw new ErrorException($str, 0, $no, $file, $line);
});

$ROOT = dirname(__DIR__);
$failures = 0;
$passed   = 0;

/**
 * Фиксирует результат проверки.
 *
 * @param string $name Что проверяли
 * @param bool $ok Прошло ли
 * @param string $detail Подробности при провале
 * @return void
 */
function idaCheck($name, $ok, $detail = '')
{
    global $passed, $failures;
    if ($ok) {
        $passed++;
        echo "  [OK]   $name\n";
    } else {
        $failures++;
        echo "  [FAIL] $name" . ($detail !== '' ? " — $detail" : '') . "\n";
    }
}

echo "\n=== Импорт: выбор действия при дубликатах доступен пользователю ===\n\n";

// ---------------------------------------------------------------------------
// Работаем только с шаблоном, который реально рендерится. Проверяем это же:
// если форма переедет в другой файл, тест обязан упасть, а не молча пройти.
// ---------------------------------------------------------------------------
$livePath = $ROOT . '/templates/dashboard.php';
$live     = file_get_contents($livePath);

idaCheck(
    'форма импорта живёт в templates/dashboard.php',
    strpos($live, 'id="uploadAccountsForm"') !== false,
    'форму перенесли — тест надо переписать на новый файл'
);

// 1. Три режима, каждый — настоящий radio
foreach (array('skip', 'update', 'error') as $mode) {
    idaCheck(
        "в форме есть переключатель duplicate_action=\"$mode\"",
        preg_match(
            '~<input[^>]*type=["\']radio["\'][^>]*name=["\']duplicate_action["\'][^>]*value=["\']' . $mode . '["\']~s',
            $live
        ) === 1
            || preg_match(
                '~<input[^>]*name=["\']duplicate_action["\'][^>]*value=["\']' . $mode . '["\'][^>]*type=["\']radio["\']~s',
                $live
            ) === 1,
        'режим недоступен пользователю'
    );
}

// 2. Никаких скрытых захардкоженных значений — иначе выбор снова станет фикцией
idaCheck(
    'duplicate_action не зашит скрытым полем',
    preg_match('~<input[^>]*type=["\']hidden["\'][^>]*name=["\']duplicate_action["\']~s', $live) !== 1
        && preg_match('~<input[^>]*name=["\']duplicate_action["\'][^>]*type=["\']hidden["\']~s', $live) !== 1,
    'скрытое поле перебивает выбор пользователя — именно так режим и был недоступен'
);

// 3. По умолчанию — самый безопасный режим
if (preg_match_all('~<input[^>]*name=["\']duplicate_action["\'][^>]*>~s', $live, $m)) {
    $checked = array();
    foreach ($m[0] as $tag) {
        if (strpos($tag, 'checked') !== false && preg_match('~value=["\']([a-z]+)["\']~', $tag, $v)) {
            $checked[] = $v[1];
        }
    }
    idaCheck(
        'по умолчанию выбран «Пропустить» (самый безопасный)',
        $checked === array('skip'),
        'по умолчанию отмечено: ' . (empty($checked) ? 'ничего' : implode(', ', $checked))
    );
} else {
    idaCheck('переключатели duplicate_action найдены', false, 'ни одного input с этим именем');
}

// ---------------------------------------------------------------------------
// 4. Подтверждение перед разрушительным режимом
// ---------------------------------------------------------------------------
$uploadPath = $ROOT . '/assets/js/modules/dashboard-upload.js';
$upload     = file_get_contents($uploadPath);

// Комментарии вырезаем, чтобы не поймать описание вместо кода.
$uploadCode = preg_replace('~/\*[^*]*\*+(?:[^/*][^*]*\*+)*/~s', '', $upload);
$uploadCode = preg_replace('~(^|[^:\\\\])//[^\n]*~m', '$1', $uploadCode);

idaCheck(
    'модуль загрузки читает выбранный режим дубликатов',
    strpos($uploadCode, 'duplicate_action') !== false,
    'без этого невозможно спросить подтверждение именно для «Обновить»'
);
idaCheck(
    'перед режимом «Обновить» спрашивается подтверждение',
    preg_match('~confirm\s*\(~', $uploadCode) === 1,
    'импорт не пишет в журнал отмены — перезапись данных без подтверждения необратима'
);

echo "\n──────────────────────────────────────────────────\n";
echo "Результат: $passed пройдено, $failures провалено\n";
echo "──────────────────────────────────────────────────\n\n";

exit($failures > 0 ? 1 : 0);
